// scripts/gen-abi.ts — regenerate the TypeScript ABI exports from the Foundry artifact.
//
//   forge build --root contracts            (Foundry >= 1.8.6)
//   pnpm --filter @mavera/scripts abi       (this script)
//
// Writes web/src/lib/abi/mavera.ts (formatted with the web package's Biome) and scripts/abi.ts
// (same content) so the page, the API routes and the scripts share the compiled ABI instead of
// hand-written copies.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const artifactPath = resolve(root, "contracts/out/Mavera.sol/Mavera.json");
const webAbiPath = resolve(root, "web/src/lib/abi/mavera.ts");
const scriptsAbiPath = resolve(root, "scripts/abi.ts");

interface Artifact {
  abi: unknown[];
  metadata?: { compiler?: { version?: string } };
}

const artifact = JSON.parse(readFileSync(artifactPath, "utf8")) as Artifact;
const compiler = artifact.metadata?.compiler?.version ?? "unknown";

function header(relativeTarget: string): string {
  return [
    `// ${relativeTarget} — GENERATED by scripts/gen-abi.ts from contracts/out/Mavera.sol/Mavera.json`,
    `// (contract Mavera, solc ${compiler}). Do not edit by hand: run \`forge build --root contracts\``,
    "// and `pnpm --filter @mavera/scripts abi` after changing contracts/src/Mavera.sol.",
    "",
  ].join("\n");
}

const body = `export const maveraAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;

writeFileSync(webAbiPath, header("web/src/lib/abi/mavera.ts") + body);
execFileSync("pnpm", ["--filter", "@mavera/web", "exec", "biome", "format", "--write", "src/lib/abi/mavera.ts"], {
  cwd: root,
  stdio: "inherit",
});
const formatted = readFileSync(webAbiPath, "utf8");
const formattedBody = formatted.slice(formatted.indexOf("export const maveraAbi"));
writeFileSync(scriptsAbiPath, header("scripts/abi.ts") + formattedBody);
console.log(`wrote ${webAbiPath}\nwrote ${scriptsAbiPath}\n(${artifact.abi.length} ABI entries, solc ${compiler})`);
